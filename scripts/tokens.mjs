// Emits src/styles/tokens.css from replica/design/tokens*.json (the single source of truth).
import { readFileSync, writeFileSync } from 'node:fs'

const light = JSON.parse(readFileSync('replica/design/tokens.json', 'utf8'))
const dark = JSON.parse(readFileSync('replica/design/tokens.dark.json', 'utf8'))

const colors = (t) => Object.entries(t.color).map(([k, v]) => `  --tl-${k}: ${v};`).join('\n')
const shared = [
  ...Object.entries(light.radius).map(([k, v]) => `  --tl-radius-${k}: ${v}px;`),
  ...Object.entries(light.shadow).map(([k, v]) => `  --tl-shadow-${k}: ${v};`),
  ...Object.entries(light.motion).map(([k, v]) => `  --tl-motion-${k}: ${v};`),
  `  --tl-font-sans: ${light.font.sans};`,
  `  --tl-tabbar: ${light.layout.tabbar}px;`,
].join('\n')

const css = `/* Generated by scripts/tokens.mjs from replica/design/tokens*.json. Do not edit by hand. */
:root {
  color-scheme: light;
${colors(light)}
${shared}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${colors(dark).replace(/^/gm, '  ')}
  }
}
:root[data-theme='dark'] {
  color-scheme: dark;
${colors(dark)}
}
`
writeFileSync('src/styles/tokens.css', css)
console.log('wrote src/styles/tokens.css')
